#!/usr/bin/env python3
"""Generate custom_components/bvg_connections/line_colors.py from the VBB GTFS feed.

Usage:
    python scripts/gen_line_colors.py              # download https://www.vbb.de/gtfs
    python scripts/gen_line_colors.py routes.txt   # use an extracted routes.txt

Only routes of BVG and S-Bahn Berlin carry colours in the feed (S and U lines);
everything else falls back to product colours defined in the template below.
"""

from __future__ import annotations

import csv
import io
from pathlib import Path
import sys
import urllib.request
import zipfile

GTFS_URL = "https://www.vbb.de/gtfs"
TARGET = (
    Path(__file__).resolve().parent.parent
    / "custom_components"
    / "bvg_connections"
    / "line_colors.py"
)
# BVG and S-Bahn Berlin GmbH
AGENCIES = {"1", "796"}
# Lines that are temporarily not in the feed but still exist.
EXTRA = {"S45": ("#CD9C53", "#FFFFFF")}

TEMPLATE = '''"""Line colours for Berlin public transport.

GENERATED by scripts/gen_line_colors.py from the VBB GTFS feed (routes.txt).
Do not edit LINE_COLORS by hand; adjust PRODUCT_COLORS or the generator instead.
"""

from __future__ import annotations

from typing import Final

LINE_COLORS: Final[dict[str, tuple[str, str]]] = {{
{lines}
}}

# Fallback colours per product (BVG / VBB corporate colours).
PRODUCT_COLORS: Final[dict[str, tuple[str, str]]] = {{
    "suburban": ("#008D4F", "#FFFFFF"),
    "subway": ("#115D91", "#FFFFFF"),
    "tram": ("#BE1414", "#FFFFFF"),
    "bus": ("#A5027D", "#FFFFFF"),
    "ferry": ("#0080BA", "#FFFFFF"),
    "regional": ("#E2001A", "#FFFFFF"),
    "express": ("#4B5257", "#FFFFFF"),
}}
DEFAULT_COLOR: Final = ("#5F6368", "#FFFFFF")


def line_color(name: str | None, product: str | None) -> tuple[str, str]:
    """Return (background, text) colour for a line."""
    if name:
        key = name.replace(" ", "").upper()
        if key in LINE_COLORS:
            return LINE_COLORS[key]
    if product and product in PRODUCT_COLORS:
        return PRODUCT_COLORS[product]
    return DEFAULT_COLOR
'''


def read_routes(source: str | None) -> list[dict[str, str]]:
    """Read routes.txt from a file or the downloaded GTFS zip."""
    if source:
        text = Path(source).read_text(encoding="utf-8-sig")
    else:
        with urllib.request.urlopen(GTFS_URL, timeout=300) as resp:
            data = resp.read()
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            text = archive.read("routes.txt").decode("utf-8-sig")
    return list(csv.DictReader(io.StringIO(text)))


def build(routes: list[dict[str, str]]) -> str:
    """Render the python module."""
    colors: dict[str, tuple[str, str]] = dict(EXTRA)
    for route in routes:
        if route.get("agency_id") not in AGENCIES or not route.get("route_color"):
            continue
        name = route["route_short_name"].replace(" ", "").upper()
        text = route.get("route_text_color") or "FFFFFF"
        colors[name] = (f"#{route['route_color'].upper()}", f"#{text.upper()}")

    def sort_key(item: tuple[str, tuple[str, str]]) -> tuple[str, int, str]:
        name = item[0]
        digits = "".join(ch for ch in name[1:] if ch.isdigit())
        return (name[0], int(digits or 0), name)

    lines = "\n".join(
        f'    "{name}": ("{bg}", "{fg}"),'
        for name, (bg, fg) in sorted(colors.items(), key=sort_key)
    )
    return TEMPLATE.format(lines=lines)


def main() -> None:
    """Entry point."""
    TARGET.write_text(build(read_routes(sys.argv[1] if len(sys.argv) > 1 else None)))
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
