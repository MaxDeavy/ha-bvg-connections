#!/usr/bin/env python3
"""Check that commit subjects follow Conventional Commits.

    python scripts/check_commits.py <base>..<head>

Allowed: `type(scope)!: description` with the types below. Merge and revert
commits generated by git are accepted as they are.
"""

from __future__ import annotations

import re
import subprocess
import sys

TYPES = (
    "feat",
    "fix",
    "docs",
    "perf",
    "refactor",
    "revert",
    "test",
    "build",
    "ci",
    "chore",
    "style",
)
PATTERN = re.compile(rf"^({'|'.join(TYPES)})(\([a-z0-9_./-]+\))?!?: \S.*$")
GENERATED = re.compile(
    r'^(Merge (pull request|branch|remote-tracking branch) |Revert ")'
)


def invalid_subjects(subjects: list[str]) -> list[str]:
    """Return the subjects that are not Conventional Commits."""
    return [s for s in subjects if not (PATTERN.match(s) or GENERATED.match(s))]


def main() -> None:
    """Entry point."""
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    log = subprocess.run(
        ["git", "log", "--format=%h %s", sys.argv[1]],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.splitlines()
    commits = [line.split(" ", 1) for line in log if line]
    bad = set(invalid_subjects([subject for _, subject in commits]))
    for sha, subject in commits:
        if subject in bad:
            print(f"::error::{sha} is not a Conventional Commit: {subject}")
    if bad:
        print(
            "Use `type(scope): description` with type one of "
            + ", ".join(TYPES)
            + " (see CONTRIBUTING.md)."
        )
        sys.exit(1)
    print(f"{len(commits)} commit(s) OK")


if __name__ == "__main__":
    main()
